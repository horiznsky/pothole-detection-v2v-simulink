model = 'PotholeDetection3D';
open_system(model);
rt = sfroot;

chartML = rt.find('-isa', 'Stateflow.EMChart', 'Path', [model '/ML_Pothole_Detector']);
if ~isempty(chartML)
    chartML.Script = sprintf([ ...
        'function pothole_prob = ML_Pothole_Detector(imu)\n' ...
        'persistent win net\n' ...
        'if isempty(win)\n' ...
        '    win = zeros(30, 3);\n' ...
        'end\n' ...
        'if isempty(net)\n' ...
        '    net = coder.loadDeepLearningNetwork(''pothole_net.mat'');\n' ...
        'end\n\n' ...
        '%% Shift 30-sample sliding window [ax, ay, az]\n' ...
        'win(1:end-1, :) = win(2:end, :);\n' ...
        'win(end, :) = imu(:)'';\n\n' ...
        '%% Mean-center window to match Colab preprocessing\n' ...
        'win_norm = win - mean(win, 1);\n\n' ...
        '%% Run trained PyTorch LSTM\n' ...
        'pothole_prob = double(predict(net, single(win_norm)));\n' ...
        'end\n']);
end

save_system(model);
disp('Trained LSTM wired into ML_Pothole_Detector. Hit Run!');