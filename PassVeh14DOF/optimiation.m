model = 'PotholeDetection3D';
open_system(model);

% 1. Speed up VisionToSuspension (16x fewer pixels + mean instead of median)
visBlk = [model '/VisionToSuspension'];
rt = sfroot;
chart = rt.find('-isa', 'Stateflow.EMChart', 'Path', visBlk);
if ~isempty(chart)
    chart.Script = sprintf([ ...
        'function Z_gnd = VisionToSuspension(img)\n' ...
        'roi_L = double(img(360:4:470, 50:4:260, :));\n' ...
        'roi_R = double(img(360:4:470, 380:4:590, :));\n' ...
        'gray_L = roi_L(:,:,1)*0.299 + roi_L(:,:,2)*0.587 + roi_L(:,:,3)*0.114;\n' ...
        'gray_R = roi_R(:,:,1)*0.299 + roi_R(:,:,2)*0.587 + roi_R(:,:,3)*0.114;\n' ...
        'mL = mean(gray_L(:)); mR = mean(gray_R(:));\n' ...
        'dL = sum(gray_L(:) > mL*1.45 | gray_L(:) < mL*0.50) / numel(gray_L);\n' ...
        'dR = sum(gray_R(:) > mR*1.45 | gray_R(:) < mR*0.50) / numel(gray_R);\n' ...
        'z_FL = -0.12 * min(1.0, max(0.0, (dL - 0.03) / 0.20));\n' ...
        'z_FR = -0.12 * min(1.0, max(0.0, (dR - 0.03) / 0.20));\n' ...
        'persistent z_hist\n' ...
        'if isempty(z_hist), z_hist = zeros(12, 2); end\n' ...
        'z_RL = z_hist(1,1); z_RR = z_hist(1,2);\n' ...
        'z_hist(1:end-1,:) = z_hist(2:end,:);\n' ...
        'z_hist(end,:) = [z_FL, z_FR];\n' ...
        'Z_gnd = [z_FL, z_FR, z_RL, z_RR];\n' ...
        'end\n']);
end

% 2. Insert a Rate Limiter between VisionToSuspension and Model/5 to stop solver stiffness
rlBlk = [model '/RoadSmoother'];
if isempty(find_system(model, 'SearchDepth', 1, 'Name', 'RoadSmoother'))
    add_block('simulink/Discontinuities/Rate Limiter', rlBlk, ...
        'RisingSlewLimit', '2.0', ...
        'FallingSlewLimit', '-2.0', ...
        'Position', [320, 235, 360, 265]);
    try delete_line(model, 'VisionToSuspension/1', 'Model/5'); catch; end
    add_line(model, 'VisionToSuspension/1', 'RoadSmoother/1', 'autorouting', 'on');
    add_line(model, 'RoadSmoother/1', 'Model/5', 'autorouting', 'on');
end

% 3. Use a stiff solver suited for 14-DOF vehicle suspension dynamics
set_param(model, 'SolverType', 'Variable-step', 'Solver', 'ode23t', 'MaxStep', '0.01');

% 4. Comment out Unreal 3D blocks while running on the MP4 video (uncomment later for 3D)
try set_param([model '/Simulation 3D Scene Configuration'], 'Commented', 'on'); catch; end
try set_param([model '/Simulation 3D Vehicle'], 'Commented', 'on'); catch; end
try set_param([model '/Simulation 3D Camera'], 'Commented', 'on'); catch; end

save_system(model);
disp('Speed optimizations applied. Hit Run now.');