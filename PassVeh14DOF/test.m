% 1. Create the external helper function (runs in native MATLAB, no Coder support package needed)
fid = fopen('run_pothole_lstm.m', 'w');
fprintf(fid, [ ...
    'function prob = run_pothole_lstm(win_norm)\n' ...
    'persistent net\n' ...
    'if isempty(net)\n' ...
    '    s = load(''pothole_net.mat'');\n' ...
    '    net = s.net;\n' ...
    'end\n' ...
    '%% Scale damped 14-DOF CG acceleration to match real smartphone IMU range\n' ...
    'scaled_win = single(win_norm * 4.0);\n' ...
    'prob = double(predict(net, scaled_win));\n' ...
    'end\n']);
fclose(fid);

% 2. Update ML_Pothole_Detector to call it via coder.extrinsic
model = 'PotholeDetection3D';
open_system(model);
rt = sfroot;

chartML = rt.find('-isa', 'Stateflow.EMChart', 'Path', [model '/ML_Pothole_Detector']);
if ~isempty(chartML)
    chartML.Script = sprintf([ ...
        'function pothole_prob = ML_Pothole_Detector(imu)\n' ...
        'coder.extrinsic(''run_pothole_lstm'');\n' ...
        'persistent win\n' ...
        'if isempty(win)\n' ...
        '    win = zeros(30, 3);\n' ...
        'end\n\n' ...
        '%% Shift 30-sample sliding window [ax, ay, az]\n' ...
        'win(1:end-1, :) = win(2:end, :);\n' ...
        'win(end, :) = imu(:)'';\n\n' ...
        '%% Mean-center window to match Colab preprocessing\n' ...
        'win_norm = win - mean(win, 1);\n\n' ...
        '%% Pre-allocate output type/size for Simulink, then call LSTM\n' ...
        'pothole_prob = 0.0;\n' ...
        'pothole_prob = run_pothole_lstm(win_norm);\n' ...
        'end\n']);
end

save_system(model);
disp('Extrinsic LSTM wrapper ready. Hit Run!');