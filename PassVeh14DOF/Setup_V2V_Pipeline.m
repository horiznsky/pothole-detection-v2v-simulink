%% Setup_V2V_Pipeline.m — Complete IMU + ML Placeholder + V2V Second Car in Simulink
model = 'PotholeDetection3D';
open_system(model);

% Helper to safely connect lines only if destination port is unconnected
safeConnect = @(src, dstBlk, dstPort) ...
    (get_param(get_param([model '/' dstBlk], 'PortHandles').Inport(dstPort), 'Line') == -1) && ...
    ~isempty(add_line(model, src, [dstBlk '/' num2str(dstPort)], 'autorouting', 'on'));

% -------------------------------------------------------------------------
% 1. Expand Bus Selector to output 3-axis Accelerometer (ax, ay, az)
% -------------------------------------------------------------------------
busSel = [model '/Bus' char(10) 'Selector'];
sigs = get_param(busSel, 'OutputSignals');
needed = {'Body.Cg.Acc.ax', 'Body.Cg.Acc.ay', 'Body.Cg.Acc.az'};
for i = 1:length(needed)
    if ~contains(sigs, needed{i})
        sigs = [sigs ',' needed{i}];
    end
end
set_param(busSel, 'OutputSignals', sigs);

% Find exact port indices for ax, ay, az
sigList = split(get_param(busSel, 'OutputSignals'), ',');
idxAx = find(strcmp(sigList, 'Body.Cg.Acc.ax'), 1);
idxAy = find(strcmp(sigList, 'Body.Cg.Acc.ay'), 1);
idxAz = find(strcmp(sigList, 'Body.Cg.Acc.az'), 1);

% -------------------------------------------------------------------------
% 2. Mux 3-Axis IMU Signals
% -------------------------------------------------------------------------
if isempty(find_system(model, 'SearchDepth', 1, 'Name', 'IMU_Mux'))
    add_block('simulink/Signal Routing/Mux', [model '/IMU_Mux'], ...
        'Inputs', '3', 'Position', [520, 400, 525, 460]);
end
safeConnect(['Bus' char(10) 'Selector/' num2str(idxAx)], 'IMU_Mux', 1);
safeConnect(['Bus' char(10) 'Selector/' num2str(idxAy)], 'IMU_Mux', 2);
safeConnect(['Bus' char(10) 'Selector/' num2str(idxAz)], 'IMU_Mux', 3);

% -------------------------------------------------------------------------
% 3. Add ML_Pothole_Detector (30-sample window + Placeholder for ONNX LSTM)
% -------------------------------------------------------------------------
mlBlk = [model '/ML_Pothole_Detector'];
if isempty(find_system(model, 'SearchDepth', 1, 'Name', 'ML_Pothole_Detector'))
    add_block('simulink/User-Defined Functions/MATLAB Function', mlBlk, ...
        'Position', [580, 405, 720, 455]);
end

rt = sfroot;
chartML = rt.find('-isa', 'Stateflow.EMChart', 'Path', mlBlk);
if ~isempty(chartML)
    chartML.Script = sprintf([ ...
        'function pothole_prob = ML_Pothole_Detector(imu)\n' ...
        '%% Maintains a 30-sample sliding window [ax, ay, az] for LSTM inference\n' ...
        'persistent win\n' ...
        'if isempty(win)\n' ...
        '    win = zeros(30, 3);\n' ...
        'end\n' ...
        'win(1:end-1, :) = win(2:end, :);\n' ...
        'win(end, :) = imu(:)'';\n\n' ...
        '%% Remove DC / gravity offset per window (matches Colab preprocessing)\n' ...
        'win_norm = win - mean(win, 1);\n\n' ...
        '%% --- PLACEHOLDER DETECTOR (Swap with ONNX LSTM once trained) ---\n' ...
        '%% Future ONNX swap:\n' ...
        '%%   persistent net; if isempty(net), net = coder.loadDeepLearningNetwork(''pothole_net.mat''); end\n' ...
        '%%   pothole_prob = double(predict(net, single(win_norm)));\n' ...
        'peak_az = max(abs(win_norm(:, 3)));\n' ...
        'pothole_prob = min(1.0, max(0.0, (peak_az - 1.5) / 3.0));\n' ...
        'end\n']);
end
safeConnect('IMU_Mux/1', 'ML_Pothole_Detector', 1);

% -------------------------------------------------------------------------
% 4. Add Clock + V2V_Hazard_Notifier (Mapping + Second Car + Braking Alert)
% -------------------------------------------------------------------------
if isempty(find_system(model, 'SearchDepth', 1, 'Name', 'SimClock'))
    add_block('simulink/Sources/Clock', [model '/SimClock'], ...
        'Position', [700, 500, 720, 520]);
end

v2vBlk = [model '/V2V_Hazard_Notifier'];
if isempty(find_system(model, 'SearchDepth', 1, 'Name', 'V2V_Hazard_Notifier'))
    add_block('simulink/User-Defined Functions/MATLAB Function', v2vBlk, ...
        'Position', [780, 415, 950, 515]);
end

chartV2V = rt.find('-isa', 'Stateflow.EMChart', 'Path', v2vBlk);
if ~isempty(chartV2V)
    chartV2V.Script = sprintf([ ...
        'function [alertActive, distToHazard, X_follower, mappedX] = V2V_Hazard_Notifier(pothole_prob, X_lead, t)\n' ...
        'persistent hazardList count followerX followerV lastT\n' ...
        'if isempty(hazardList)\n' ...
        '    hazardList = zeros(1, 50);\n' ...
        '    count = 0;\n' ...
        '    followerX = -25.0; %% Second car starts 25 m behind lead car\n' ...
        '    followerV = 14.0;  %% Cruising speed (m/s)\n' ...
        '    lastT = 0.0;\n' ...
        'end\n' ...
        'dt = max(0.0, t - lastT);\n' ...
        'lastT = t;\n\n' ...
        '%% 1. Map pothole coordinate when ML probability > 0.70\n' ...
        'if pothole_prob > 0.70\n' ...
        '    if count == 0 || abs(X_lead - hazardList(count)) > 3.0\n' ...
        '        if count < 50\n' ...
        '            count = count + 1;\n' ...
        '            hazardList(count) = X_lead;\n' ...
        '        end\n' ...
        '    end\n' ...
        'end\n\n' ...
        '%% 2. Check distance from Second Car to nearest upcoming mapped pothole\n' ...
        'alertActive = 0;\n' ...
        'distToHazard = 999.0;\n' ...
        'mappedX = 0.0;\n' ...
        'for i = 1:count\n' ...
        '    d = hazardList(i) - followerX;\n' ...
        '    if d > 0 && d < distToHazard\n' ...
        '        distToHazard = d;\n' ...
        '        mappedX = hazardList(i);\n' ...
        '    end\n' ...
        'end\n\n' ...
        '%% 3. V2V Notification & Automated Deceleration within 30 m\n' ...
        'if distToHazard <= 30.0\n' ...
        '    alertActive = 1;\n' ...
        '    followerV = max(6.0, followerV - 4.0 * dt);\n' ...
        'else\n' ...
        '    followerV = min(14.0, followerV + 2.0 * dt);\n' ...
        'end\n' ...
        'followerX = followerX + followerV * dt;\n' ...
        'X_follower = followerX;\n' ...
        'end\n']);
end

safeConnect('ML_Pothole_Detector/1', 'V2V_Hazard_Notifier', 1);
safeConnect(['Bus' char(10) 'Selector/1'], 'V2V_Hazard_Notifier', 2); % InertFrm.Cg.Disp.X
safeConnect('SimClock/1', 'V2V_Hazard_Notifier', 3);

% -------------------------------------------------------------------------
% 5. Add Live Displays & Scope for Verification
% -------------------------------------------------------------------------
displays = { ...
    'V2V_Alert_Flag',   [1020, 400, 1110, 430], 1; ...
    'Dist_To_Pothole',  [1020, 445, 1110, 475], 2; ...
    'Follower_Car_X',   [1020, 490, 1110, 520], 3; ...
    'Last_Mapped_X',    [1020, 535, 1110, 565], 4};

for i = 1:size(displays, 1)
    dName = displays{i, 1};
    if isempty(find_system(model, 'SearchDepth', 1, 'Name', dName))
        add_block('simulink/Sinks/Display', [model '/' dName], 'Position', displays{i, 2});
    end
    safeConnect(['V2V_Hazard_Notifier/' num2str(displays{i, 3})], dName, 1);
end

if isempty(find_system(model, 'SearchDepth', 1, 'Name', 'V2V_Scope'))
    add_block('simulink/Sinks/Scope', [model '/V2V_Scope'], ...
        'NumInputPorts', '3', 'Position', [1030, 320, 1080, 380]);
end
safeConnect('ML_Pothole_Detector/1', 'V2V_Scope', 1);
safeConnect('V2V_Hazard_Notifier/1', 'V2V_Scope', 2);
safeConnect('V2V_Hazard_Notifier/2', 'V2V_Scope', 3);

set_param(model, 'ZoomFactor', 'FitSystem');
save_system(model);
disp('MATLAB/Simulink IMU + ML Placeholder + V2V Second Car pipeline is ready!');