model = 'PotholeDetection3D';
open_system(model);
rt = sfroot;

% 1. Let tire drops hit sharper (increase Rate Limiter slew rate)
try
    set_param([model '/RoadSmoother'], 'RisingSlewLimit', '6.0', 'FallingSlewLimit', '-6.0');
catch; end

% 2. Lower IMU placeholder deadzone (0.4 m/s^2 instead of 1.5 m/s^2)
chartML = rt.find('-isa', 'Stateflow.EMChart', 'Path', [model '/ML_Pothole_Detector']);
if ~isempty(chartML)
    chartML.Script = sprintf([ ...
        'function pothole_prob = ML_Pothole_Detector(imu)\n' ...
        'persistent win\n' ...
        'if isempty(win), win = zeros(30, 3); end\n' ...
        'win(1:end-1, :) = win(2:end, :);\n' ...
        'win(end, :) = imu(:)'';\n' ...
        'win_norm = win - mean(win, 1);\n' ...
        'peak_az = max(abs(win_norm(:, 3)));\n' ...
        'pothole_prob = min(1.0, max(0.0, (peak_az - 0.35) / 1.2));\n' ...
        'end\n']);
end

% 3. Boost Vision placeholder sensitivity for bright puddles & dark cavities
chartVis = rt.find('-isa', 'Stateflow.EMChart', 'Path', [model '/Vision_ML_Detector']);
if ~isempty(chartVis)
    chartVis.Script = sprintf([ ...
        'function vision_prob = Vision_ML_Detector(img)\n' ...
        'roi = double(img(280:4:450, 100:4:540, :));\n' ...
        'gray = roi(:,:,1)*0.299 + roi(:,:,2)*0.587 + roi(:,:,3)*0.114;\n' ...
        'm = mean(gray(:));\n' ...
        'anomalyRatio = sum(gray(:) > m*1.35 | gray(:) < m*0.55) / numel(gray);\n' ...
        'vision_prob = min(1.0, max(0.0, (anomalyRatio - 0.02) / 0.08));\n' ...
        'end\n']);
end

save_system(model);
disp('Thresholds tuned. Hit Run and click Autoscale on V2V_Scope.');