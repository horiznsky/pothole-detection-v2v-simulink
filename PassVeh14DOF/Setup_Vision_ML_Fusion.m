%% Setup_Vision_ML_Fusion.m — Add Vision ML Placeholder + Late Sensor Fusion
model = 'PotholeDetection3D';
open_system(model);

safeConnect = @(src, dstBlk, dstPort) ...
    (get_param(get_param([model '/' dstBlk], 'PortHandles').Inport(dstPort), 'Line') == -1) && ...
    ~isempty(add_line(model, src, [dstBlk '/' num2str(dstPort)], 'autorouting', 'on'));

rt = sfroot;

% -------------------------------------------------------------------------
% 1. Add Vision_ML_Detector (Placeholder for Colab-trained CNN / YOLO ONNX)
% -------------------------------------------------------------------------
visMLBlk = [model '/Vision_ML_Detector'];
if isempty(find_system(model, 'SearchDepth', 1, 'Name', 'Vision_ML_Detector'))
    add_block('simulink/User-Defined Functions/MATLAB Function', visMLBlk, ...
        'Position', [580, 310, 720, 360]);
end

chartVisML = rt.find('-isa', 'Stateflow.EMChart', 'Path', visMLBlk);
if ~isempty(chartVisML)
    chartVisML.Script = sprintf([ ...
        'function vision_prob = Vision_ML_Detector(img)\n' ...
        '%% Input: 480x640x3 uint8 RGB frame\n' ...
        '%% --- FUTURE ONNX SWAP (Colab MobileNetV2 / YOLOv8-cls) ---\n' ...
        '%%   persistent vnet;\n' ...
        '%%   if isempty(vnet), vnet = coder.loadDeepLearningNetwork(''pothole_vision_net.mat''); end\n' ...
        '%%   imgResized = single(imresize(img, [224 224])) / 255.0;\n' ...
        '%%   vision_prob = double(predict(vnet, imgResized));\n\n' ...
        '%% --- PLACEHOLDER DETECTOR (Look-ahead road ROI) ---\n' ...
        'roi = double(img(260:4:420, 120:4:520, :));\n' ...
        'gray = roi(:,:,1)*0.299 + roi(:,:,2)*0.587 + roi(:,:,3)*0.114;\n' ...
        'm = mean(gray(:));\n' ...
        'anomalyRatio = sum(gray(:) > m*1.45 | gray(:) < m*0.50) / numel(gray);\n' ...
        'vision_prob = min(1.0, max(0.0, (anomalyRatio - 0.04) / 0.18));\n' ...
        'end\n']);
end

% Feed Vision_ML_Detector from Camera Toggle (switches between 3D Cam and MP4)
safeConnect('Camera Toggle/1', 'Vision_ML_Detector', 1);

% -------------------------------------------------------------------------
% 2. Add Sensor_Fusion Block (Time-aligned Vision Look-Ahead + IMU Impact)
% -------------------------------------------------------------------------
fuseBlk = [model '/Sensor_Fusion'];
if isempty(find_system(model, 'SearchDepth', 1, 'Name', 'Sensor_Fusion'))
    add_block('simulink/User-Defined Functions/MATLAB Function', fuseBlk, ...
        'Position', [750, 355, 860, 415]);
end

chartFuse = rt.find('-isa', 'Stateflow.EMChart', 'Path', fuseBlk);
if ~isempty(chartFuse)
    chartFuse.Script = sprintf([ ...
        'function fused_prob = Sensor_Fusion(vision_prob, imu_prob)\n' ...
        '%% Camera sees pothole ~0.5-1.5s BEFORE the tires hit it.\n' ...
        '%% Hold peak vision confidence briefly so it aligns with the IMU jolt.\n' ...
        'persistent vis_hold\n' ...
        'if isempty(vis_hold), vis_hold = 0.0; end\n' ...
        'vis_hold = max(vision_prob, vis_hold * 0.96); %% ~1.5s decay at 60 Hz\n\n' ...
        '%% Late-fusion confidence score\n' ...
        'fused_prob = min(1.0, 0.45 * vis_hold + 0.55 * imu_prob);\n' ...
        'end\n']);
end

safeConnect('Vision_ML_Detector/1', 'Sensor_Fusion', 1);
safeConnect('ML_Pothole_Detector/1', 'Sensor_Fusion', 2);

% -------------------------------------------------------------------------
% 3. Rewire V2V_Hazard_Notifier & V2V_Scope to use Fused Probability
% -------------------------------------------------------------------------
try delete_line(model, 'ML_Pothole_Detector/1', 'V2V_Hazard_Notifier/1'); catch; end
try delete_line(model, 'ML_Pothole_Detector/1', 'V2V_Scope/1'); catch; end

safeConnect('Sensor_Fusion/1', 'V2V_Hazard_Notifier', 1);
safeConnect('Sensor_Fusion/1', 'V2V_Scope', 1);

set_param(model, 'ZoomFactor', 'FitSystem');
save_system(model);
disp('Vision ML placeholder + Sensor Fusion wired into V2V_Hazard_Notifier!');