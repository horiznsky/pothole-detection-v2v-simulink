model = 'PotholeDetection3D';
open_system(model);

% 1. Create VisionToSuspension block if missing
visBlk = [model '/VisionToSuspension'];
if isempty(find_system(model, 'SearchDepth', 1, 'Name', 'VisionToSuspension'))
    add_block('simulink/User-Defined Functions/MATLAB Function', visBlk, ...
        'Position', [200, 220, 350, 280]);
end

% 2. Automatically inject the code into the MATLAB Function block
rt = sfroot;
chart = rt.find('-isa', 'Stateflow.EMChart', 'Path', visBlk);
if ~isempty(chart)
    chart.Script = sprintf([ ...
        'function Z_gnd = VisionToSuspension(img)\n' ...
        'roi_L = img(400:480, 150:280, :);\n' ...
        'roi_R = img(400:480, 360:490, :);\n' ...
        'gray_L = double(roi_L(:,:,1))*0.299 + double(roi_L(:,:,2))*0.587 + double(roi_L(:,:,3))*0.114;\n' ...
        'gray_R = double(roi_R(:,:,1))*0.299 + double(roi_R(:,:,2))*0.587 + double(roi_R(:,:,3))*0.114;\n' ...
        'density_L = sum(gray_L(:) < (mean(gray_L(:)) * 0.55)) / numel(gray_L);\n' ...
        'density_R = sum(gray_R(:) < (mean(gray_R(:)) * 0.55)) / numel(gray_R);\n' ...
        'z_FL = -0.12 * min(1.0, density_L / 0.15);\n' ...
        'z_FR = -0.12 * min(1.0, density_R / 0.15);\n' ...
        'persistent z_history\n' ...
        'if isempty(z_history)\n' ...
        '    z_history = zeros(12, 2);\n' ...
        'end\n' ...
        'z_RL = z_history(1, 1);\n' ...
        'z_RR = z_history(1, 2);\n' ...
        'z_history(1:end-1, :) = z_history(2:end, :);\n' ...
        'z_history(end, :) = [z_FL, z_FR];\n' ...
        'Z_gnd = [z_FL, z_FR, z_RL, z_RR];\n' ...
        'end\n']);
end

% 3. Disconnect Constant4 from Model Port 5 and wire VisionToSuspension
try delete_line(model, 'Constant4/1', 'Model/5'); catch; end
try add_line(model, 'Real Dashcam Input/1', 'VisionToSuspension/1', 'autorouting', 'on'); catch; end
try add_line(model, 'VisionToSuspension/1', 'Model/5', 'autorouting', 'on'); catch; end

% 4. Highlight and zoom to fit so you can see it right away
hilite_system(visBlk);
set_param(model, 'ZoomFactor', 'FitSystem');
save_system(model);
disp('VisionToSuspension created, populated, and wired.');